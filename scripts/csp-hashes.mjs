// Next.js inlines bootstrap <script> tags in every exported HTML page. A static export can't
// use CSP nonces, so we hash those scripts after `next build` and hand the hashes to nginx.
// This keeps `script-src 'self'` strict (no 'unsafe-inline').
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const INLINE_SCRIPT = /<script(?![^>]*\bsrc\s*=)[^>]*>([\s\S]*?)<\/script>/gi;

export function inlineScriptHashes(html) {
  const hashes = new Set();
  for (const [, body] of html.matchAll(INLINE_SCRIPT)) {
    if (body.length === 0) continue;
    hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
  }
  return hashes;
}

function htmlFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return htmlFiles(path);
    return entry.name.endsWith(".html") ? [path] : [];
  });
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const outDir = join(root, "out");
  const target = join(root, "nginx", "generated", "csp-hashes.conf");

  const hashes = new Set();
  for (const file of htmlFiles(outDir)) {
    for (const hash of inlineScriptHashes(readFileSync(file, "utf8"))) hashes.add(hash);
  }

  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(
    target,
    `# Generated by scripts/csp-hashes.mjs after \`next build\`. Do not edit.\n` +
      `map $host $csp_script_hashes {\n  default "${[...hashes].sort().join(" ")}";\n}\n`,
  );
  console.log(`csp-hashes: ${hashes.size} inline script hash(es) -> ${target}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
